import type { EngineId } from "./contract";

/** Placeholders the template carries, in the order they must all resolve. */
const PLACEHOLDERS = [
  "{{AETHER_OFF_KEY}}",
  "{{AETHER_BEACON_TOKEN}}",
  "{{AETHER_BEACON_TOPIC}}",
  /* Which of the three engines this notebook is. Tagged into every beacon
     announcement so a client can attribute a tunnel URL to a slot. */
  "{{AETHER_SLOT}}",
] as const;

export interface NotebookSecrets {
  offKey: string;
  beaconToken: string;
  beaconTopic: string;
  /** "a" | "b" | "c" — stamped into every beacon announcement. */
  slot: string;
}

/** webhook.site token, from an explicit override or parsed out of BEACON_URL. */
function beaconTokenFromEnv(): string {
  const explicit = process.env.ENGINE_BEACON_TOKEN;
  if (explicit) return explicit;
  const url = process.env.BEACON_URL ?? "";
  const m = url.match(/webhook\.site\/(?:token\/)?([0-9a-f-]{36})/i);
  return m ? m[1] : "";
}

/** ntfy topic, from an explicit override or parsed out of BEACON_BACKUP_URL. */
function beaconTopicFromEnv(): string {
  const explicit = process.env.ENGINE_BEACON_TOPIC;
  if (explicit) return explicit;
  const url = process.env.BEACON_BACKUP_URL ?? "";
  const m = url.match(/ntfy\.sh\/([^/?#]+)/i);
  return m ? m[1] : "";
}

/** Decode and integrity-check the stored template. Throws on any byte drift. */
export function aetherNotebookTemplate(): string {
  const decoded = Buffer.from(B64, "base64").toString("utf8");
  const h = createHash("sha256").update(decoded, "utf8").digest("hex");
  if (h !== AETHER_NOTEBOOK_SHA256) {
    throw new Error(
      `AETHER engine source integrity FAILED (got ${h}, want ${AETHER_NOTEBOOK_SHA256}) — refusing to push.`,
    );
  }
  JSON.parse(decoded); // throws if not valid JSON/notebook
  return decoded;
}

/** Render the template with explicit secrets. Pure — used by tests. */
export function renderAetherNotebook(secrets: NotebookSecrets): string {
  const template = aetherNotebookTemplate();
  const values: Record<string, string> = {
    "{{AETHER_OFF_KEY}}": secrets.offKey,
    "{{AETHER_BEACON_TOKEN}}": secrets.beaconToken,
    "{{AETHER_BEACON_TOPIC}}": secrets.beaconTopic,
    "{{AETHER_SLOT}}": secrets.slot,
  };
  /* Fail closed: pushing a notebook with an unresolved placeholder would boot an
     engine that cannot authenticate its own /off route. */
  for (const key of PLACEHOLDERS) {
    if (!values[key]) {
      const envName =
        key === "{{AETHER_OFF_KEY}}"
          ? "ENGINE_OFF_KEY"
          : key === "{{AETHER_BEACON_TOKEN}}"
            ? "ENGINE_BEACON_TOKEN (or a webhook.site BEACON_URL)"
            : key === "{{AETHER_BEACON_TOPIC}}"
              ? "ENGINE_BEACON_TOPIC (or an ntfy.sh BEACON_BACKUP_URL)"
              : "engine slot (internal — a bug, not a config problem)";
      throw new Error(`Cannot render the engine notebook: ${envName} is not configured on this server.`);
    }
  }
  let out = template;
  for (const key of PLACEHOLDERS) out = out.split(key).join(values[key]);
  return out;
}

/**
 * The notebook to push, with this deployment's secrets substituted.
 * Throws if the template was tampered with or a secret is missing.
 */
export function getAetherNotebook(slot: EngineId): string {
  return renderAetherNotebook({
    offKey: process.env.ENGINE_OFF_KEY ?? "",
    beaconToken: beaconTokenFromEnv(),
    beaconTopic: beaconTopicFromEnv(),
    slot,
  });
}
